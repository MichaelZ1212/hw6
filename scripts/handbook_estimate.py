"""Problem 2: count the tokens in data/shop_handbook.md and estimate what it costs to send
the handbook to gpt-6-luna on every call, with and without prompt caching.

Token counts use tiktoken's o200k_base encoding (the tokenizer used by OpenAI's current
GPT model family). Prices come from data/prices.json. Writes output/handbook_estimate.md.

Usage:  python scripts/handbook_estimate.py
"""

from __future__ import annotations

import json
from pathlib import Path

import tiktoken

ROOT = Path(__file__).resolve().parent.parent
HANDBOOK = ROOT / "data" / "shop_handbook.md"
PRICES = ROOT / "data" / "prices.json"
OUT = ROOT / "output" / "handbook_estimate.md"
MODEL = "gpt-6-luna"
ENCODING = "o200k_base"
CALLS = 1000


def usd(x: float) -> str:
    return f"${x:,.6f}" if x < 0.01 else f"${x:,.4f}"


def main() -> None:
    text = HANDBOOK.read_text(encoding="utf-8")
    tokens = len(tiktoken.get_encoding(ENCODING).encode(text))
    p = json.loads(PRICES.read_text(encoding="utf-8"))[MODEL]

    per_tok = {k: v / 1_000_000 for k, v in p.items()}
    no_cache_1 = tokens * per_tok["input_per_1m"]
    no_cache_n = no_cache_1 * CALLS
    write_1 = tokens * per_tok["cache_write_per_1m"]
    read_1 = tokens * per_tok["cached_input_per_1m"]
    cached_n = write_1 + read_1 * (CALLS - 1)
    saved = no_cache_n - cached_n

    lines = text.splitlines()
    md = f"""# Handbook cost estimate

How much does it cost to send `data/shop_handbook.md` to **{MODEL}** on every call?
Generated by `scripts/handbook_estimate.py`.

## 1. Size of the handbook

| Measure | Value |
|---|---:|
| Characters | {len(text):,} |
| Words | {len(text.split()):,} |
| Lines | {len(lines):,} |
| **Tokens ({ENCODING})** | **{tokens:,}** |

**How the tokens were counted:** the whole file was read as UTF-8 text and encoded with
`tiktoken`'s `{ENCODING}` tokenizer, the encoding used by OpenAI's current GPT models,
then the tokens were counted. That works out to {len(text) / tokens:.1f} characters per token.
The usual rule of thumb of about 4 characters per token would give only {len(text) / 4:,.0f} tokens.
The handbook packs denser than plain prose because it is full of SKU codes, prices, numbers,
tables, and Markdown symbols, which split into many short tokens. When the handbook goes out as a
system message, the API adds a few formatting tokens, so the billed number will be slightly higher.

## 2. Prices ({MODEL}, from `data/prices.json`)

| Price type | Per 1M tokens | Per token |
|---|---:|---:|
| Input (not cached) | ${p['input_per_1m']} | ${per_tok['input_per_1m']:.9f} |
| Cache write (first time the prefix is stored) | ${p['cache_write_per_1m']} | ${per_tok['cache_write_per_1m']:.9f} |
| Cached input (cache hit) | ${p['cached_input_per_1m']} | ${per_tok['cached_input_per_1m']:.9f} |
| Output | ${p['output_per_1m']} | ${per_tok['output_per_1m']:.9f} |

Only the handbook's input tokens are priced here. The vendor document and the model's answer
are extra and change from call to call.

## 3. Cost of the handbook alone

### Without caching (every call pays full input price)

- 1 call: {tokens:,} x ${p['input_per_1m']} / 1,000,000 = **{usd(no_cache_1)}**
- {CALLS:,} calls: {usd(no_cache_1)} x {CALLS:,} = **{usd(no_cache_n)}**

### With caching (first call writes the cache, the rest read it)

- 1st call (cache write): {tokens:,} x ${p['cache_write_per_1m']} / 1,000,000 = **{usd(write_1)}**
- Each later call (cache hit): {tokens:,} x ${p['cached_input_per_1m']} / 1,000,000 = **{usd(read_1)}**
- {CALLS:,} calls: {usd(write_1)} + {CALLS - 1:,} x {usd(read_1)} = **{usd(cached_n)}**

### Side by side

| Scenario | 1 call | {CALLS:,} calls |
|---|---:|---:|
| No caching | {usd(no_cache_1)} | {usd(no_cache_n)} |
| With caching | {usd(write_1)} (write) / {usd(read_1)} (hit) | {usd(cached_n)} |
| **Savings** | | **{usd(saved)} ({saved / no_cache_n:.1%})** |

## 4. What caching saves

- A single cached call is a bit **more** expensive than an uncached one
  ({usd(write_1)} vs {usd(no_cache_1)}), because storing the cache costs
  ${p['cache_write_per_1m']}/1M instead of ${p['input_per_1m']}/1M.
- Every later call that hits the cache pays ${p['cached_input_per_1m']}/1M instead of
  ${p['input_per_1m']}/1M, which is **{1 - p['cached_input_per_1m'] / p['input_per_1m']:.0%} cheaper**.
- Caching pays for itself from the 2nd call on. Over {CALLS:,} calls the handbook bill drops from
  {usd(no_cache_n)} to {usd(cached_n)}, about **{no_cache_n / cached_n:.1f}x cheaper**.
- In dollars the numbers are small because {MODEL} is cheap. The pattern still matters,
  because the handbook is sent on every call, so it makes up most of the input tokens.

**Assumptions to check against real usage later:**
1. The instructions + handbook prefix (agent instructions first, then the full handbook) never changes, so every call shares the same prefix.
2. Calls come close enough together that the cache stays warm. If the cache expires, the next call
   pays the write price again.
3. The billed token count will be a little above {tokens:,} because of message formatting tokens.
   The real API response (`usage.prompt_tokens` and `cached_tokens`) is the number to compare against.
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(md, encoding="utf-8")
    print(f"tokens={tokens}  no_cache_1000={no_cache_n:.4f}  cached_1000={cached_n:.4f}  -> {OUT}")


if __name__ == "__main__":
    main()
